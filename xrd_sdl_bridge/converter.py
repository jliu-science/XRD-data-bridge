"""Non-destructive powder XRD format converter.

Reads  : .hdf5 / .h5 (Anton Paar), .xrdml (PANalytical), .xy / .xye, .dat, .asc
         (PANalytical 2-column or Rigaku *TYPE_RAW) and .raw (Bruker RAW1.01).
Writes : .xrdml, .asc, .xy, .dat, .raw (Bruker RAW1.01)  (+ optional anode wavelength re-mapping via Bragg's law).

All read operations open source files strictly in read-only mode.  Write operations
never touch .hdf5/.h5 files and refuse to overwrite an existing .xy/.xye/.xrdml/.dat
file unless that file was generated by this bridge (identified by BRIDGE_MARKER).
"""

from __future__ import annotations

import datetime as dt
import os
import re
import struct
from decimal import Decimal
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

import numpy as np

# Binary raw extensions that must never be written at all.
PROTECTED_EXTENSIONS = {".hdf5", ".h5"}
# Formats that may be raw instrument files: only overwrite if the bridge made them.
GUARDED_TEXT_EXTENSIONS = {".xy", ".xye", ".xrdml", ".dat", ".raw"}
# Marker string embedded in every .xrdml / .xy / .dat / .raw this bridge writes.
BRIDGE_MARKER = "SDL Bridge"

INPUT_EXTENSIONS = {".hdf5", ".h5", ".xrdml", ".xy", ".xye", ".dat", ".asc", ".raw"}
OUTPUT_FORMATS = ("xrdml", "asc", "xy", "dat", "raw")
FORMAT_EXTENSION = {"xrdml": ".xrdml", "asc": ".asc", "xy": ".xy", "dat": ".dat", "raw": ".raw"}

# Standard X-ray tube characteristic wavelengths in Angstroms (ICDD / PANalytical conventions).
ANODE_WAVELENGTHS: dict[str, dict[str, float]] = {
    "Cu": {"kAlpha1": 1.540598, "kAlpha2": 1.544426, "kBeta": 1.392250, "ratio": 0.500000},
    "Co": {"kAlpha1": 1.788996, "kAlpha2": 1.792835, "kBeta": 1.620830, "ratio": 0.500000},
    "Mo": {"kAlpha1": 0.709319, "kAlpha2": 0.713609, "kBeta": 0.632305, "ratio": 0.500000},
    "Cr": {"kAlpha1": 2.289760, "kAlpha2": 2.293663, "kBeta": 2.084920, "ratio": 0.500000},
    "Fe": {"kAlpha1": 1.936042, "kAlpha2": 1.939980, "kBeta": 1.756610, "ratio": 0.500000},
    "Ag": {"kAlpha1": 0.559421, "kAlpha2": 0.563813, "kBeta": 0.497082, "ratio": 0.500000},
}

_ANGLE_KEYS = (
    "2theta",
    "twotheta",
    "two_theta",
    "position_2theta",
    "positions_2theta",
    "positions",
    "angle",
    "theta2",
    "gonio",
    "x",
)

_INTENSITY_KEYS = (
    "intensity_counts",
    "intensities",
    "intensity",
    "counts",
    "detector",
    "signal",
    "y",
    "data",
)


@dataclass
class ScanData:
    """Normalized 1D powder XRD scan container."""

    name: str
    source_path: str
    source_format: str  # "hdf5" or "xy"
    two_theta: np.ndarray
    intensity: np.ndarray
    anode: str = "Cu"
    wavelength_ka1: float | None = None
    counting_time: float = 1.0
    metadata: dict[str, Any] = field(default_factory=dict)

    def resolved_wavelengths(self, anode_override: str | None = None) -> tuple[str, dict[str, float]]:
        """Resolve anode name and K-alpha/beta wavelengths."""
        anode_key = _normalize_anode(anode_override or self.anode)
        wl = dict(ANODE_WAVELENGTHS[anode_key])
        if self.wavelength_ka1 is not None and anode_override is None:
            wl["kAlpha1"] = float(self.wavelength_ka1)
        return anode_key, wl


def _normalize_anode(raw: Any) -> str:
    if not raw:
        return "Cu"
    text = str(raw).strip()
    for key in ANODE_WAVELENGTHS:
        if key.lower() == text.lower() or text.lower().startswith(key.lower()):
            return key
    return "Cu"


def _infer_anode_from_wavelength(wl: float | None) -> str | None:
    if wl is None:
        return None
    best_key = None
    best_diff = 1e9
    for key, vals in ANODE_WAVELENGTHS.items():
        diff = abs(vals["kAlpha1"] - wl)
        if diff < best_diff:
            best_diff = diff
            best_key = key
    return best_key if best_diff < 0.05 else None


def fmt_num(value: float) -> str:
    """Lossless text for a float: integers stay integers, everything else uses the shortest
    decimal that parses back to exactly the same IEEE-754 value (no rounding, no truncation)."""
    f = float(value)
    if f.is_integer() and abs(f) < 1e15:
        return str(int(f))
    return np.format_float_positional(f, unique=True, trim="-")


def is_exactly_uniform(two_theta: np.ndarray) -> bool:
    """True only if start/end + point count reproduce every 2Theta value (to 1e-9 deg)."""
    if two_theta.size < 2:
        return False
    rebuilt = np.linspace(float(two_theta[0]), float(two_theta[-1]), two_theta.size)
    return bool(np.max(np.abs(rebuilt - two_theta)) <= 1e-9)


def normalize_anode(raw: Any) -> str:
    """Public alias: map free text ('Cu', 'cu ka', 'Co') to an ANODE_WAVELENGTHS key."""
    return _normalize_anode(raw)


def is_bridge_generated(path: str | Path) -> bool:
    """True if the file's header carries BRIDGE_MARKER (i.e. this bridge wrote it)."""
    try:
        with Path(path).open("rb") as fh:
            head = fh.read(4096)
    except OSError:
        return False
    return BRIDGE_MARKER.encode("ascii") in head


def _guard_output_path(out_path: Path) -> None:
    ext = out_path.suffix.lower()
    if ext in PROTECTED_EXTENSIONS:
        raise ValueError(
            f"Safety guard: refusing to write over protected raw format '{out_path.suffix}' ({out_path})"
        )
    if ext in GUARDED_TEXT_EXTENSIONS and out_path.exists() and not is_bridge_generated(out_path):
        raise ValueError(
            f"Safety guard: {out_path.name} already exists and was not created by the bridge "
            "(possible raw instrument file) - refusing to overwrite"
        )


def _decode_attr(val: Any) -> Any:
    if isinstance(val, bytes):
        return val.decode("utf-8", errors="replace")
    if isinstance(val, np.ndarray):
        if val.size == 1:
            return _decode_attr(val.item())
        return val.tolist()
    if isinstance(val, (np.floating, np.integer)):
        return val.item()
    return val


def read_xy_file(filepath: str | Path, default_anode: str = "Cu", source_format: str = "xy") -> list[ScanData]:
    """Read a plain-text 2-column .xy/.xye/.txt/.dat/.asc file without modifying it.

    Falls back to the single-column layout (first numeric line = start step stop,
    followed by intensities) used by some .dat files.
    """
    path = Path(filepath)
    if not path.is_file():
        raise FileNotFoundError(f"XY file not found: {path}")

    angles: list[float] = []
    counts: list[float] = []
    metadata: dict[str, Any] = {}
    detected_wl: float | None = None
    detected_anode: str | None = None
    counting_time = 1.0

    num_pair_re = re.compile(
        r"^\s*([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)\s*[,;\t ]+\s*"
        r"([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)"
    )

    numeric_rows: list[list[float]] = []
    num_token_re = re.compile(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?")

    with path.open("r", encoding="utf-8", errors="replace") as fh:
        for raw_line in fh:
            line = raw_line.strip()
            if not line:
                continue
            if not line.startswith(("#", "!", "//", ";")) and re.fullmatch(r"[\d\s.,;eE+\-\t]+", line):
                numeric_rows.append([float(t) for t in num_token_re.findall(line)])
            if line.startswith(("#", "!", "//", ";")):
                comment = line.lstrip("#!/; ").strip()
                if ":" in comment:
                    k, v = comment.split(":", 1)
                    k_clean = k.strip().lower()
                    v_clean = v.strip()
                    metadata[k.strip()] = v_clean
                    if "wavelength" in k_clean or "lambda" in k_clean:
                        try:
                            detected_wl = float(re.findall(r"[0-9]+\.[0-9]+", v_clean)[0])
                        except (IndexError, ValueError):
                            pass
                    elif "anode" in k_clean or "tube" in k_clean:
                        detected_anode = _normalize_anode(v_clean)
                    elif "count" in k_clean and "time" in k_clean:
                        try:
                            counting_time = float(re.findall(r"[0-9]+(?:\.[0-9]+)?", v_clean)[0])
                        except (IndexError, ValueError):
                            pass
                continue

            m = num_pair_re.match(line)
            if m:
                angles.append(float(m.group(1)))
                counts.append(float(m.group(2)))

    single_col = sum(1 for r in numeric_rows if len(r) == 1)
    if (len(angles) < 5 or single_col > len(numeric_rows) // 2) and numeric_rows and len(numeric_rows[0]) >= 3:
        # Single-column layout: header "start step stop", then one intensity per value.
        start, step, stop = numeric_rows[0][:3]
        vals = [v for r in numeric_rows[1:] for v in r]
        if len(vals) >= 5 and step > 0:
            angles = list(start + np.arange(len(vals)) * step)
            counts = vals

    if len(angles) < 5:
        raise ValueError(f"Insufficient numeric 2Theta/Intensity points ({len(angles)}) in {path.name}")

    two_theta = np.asarray(angles, dtype=np.float64)
    intensity = np.asarray(counts, dtype=np.float64)
    order = np.argsort(two_theta)
    two_theta = two_theta[order]
    intensity = intensity[order]

    inferred_anode = detected_anode or _infer_anode_from_wavelength(detected_wl) or _normalize_anode(default_anode)

    return [
        ScanData(
            name=path.stem,
            source_path=str(path),
            source_format=source_format,
            two_theta=two_theta,
            intensity=intensity,
            anode=inferred_anode,
            wavelength_ka1=detected_wl,
            counting_time=counting_time,
            metadata=metadata,
        )
    ]


def inspect_hdf5_tree(filepath: str | Path) -> dict[str, Any]:
    """Inspect the full hierarchical tree and attributes of an .hdf5/.h5 file (read-only)."""
    import h5py

    path = Path(filepath)
    if not path.is_file():
        raise FileNotFoundError(f"HDF5 file not found: {path}")

    def walk_node(node: Any, node_path: str) -> dict[str, Any]:
        attrs = {str(k): _decode_attr(v) for k, v in node.attrs.items()}
        if isinstance(node, h5py.Dataset):
            return {
                "path": node_path,
                "name": node_path.rsplit("/", 1)[-1] or "/",
                "kind": "dataset",
                "shape": list(node.shape),
                "dtype": str(node.dtype),
                "attrs": attrs,
            }
        children = [walk_node(node[key], f"{node_path.rstrip('/')}/{key}") for key in node.keys()]
        return {
            "path": node_path,
            "name": node_path.rsplit("/", 1)[-1] or "/",
            "kind": "group",
            "attrs": attrs,
            "children": children,
        }

    with h5py.File(path, "r") as h5f:
        return {
            "file": path.name,
            "path": str(path),
            "tree": walk_node(h5f, "/"),
        }


def _collect_group_attrs(h5f: Any, group_path: str) -> dict[str, Any]:
    """Merge attributes from root down to the target group."""
    merged: dict[str, Any] = {}
    for k, v in h5f.attrs.items():
        merged[str(k)] = _decode_attr(v)
    if group_path and group_path != "/":
        parts = [p for p in group_path.strip("/").split("/") if p]
        cur = h5f
        for part in parts:
            cur = cur[part]
            for k, v in cur.attrs.items():
                merged[str(k)] = _decode_attr(v)
    return merged


def _match_key_priority(name: str, candidates: tuple[str, ...]) -> int | None:
    low = name.lower().strip()
    for idx, cand in enumerate(candidates):
        if low == cand:
            return idx
    for idx, cand in enumerate(candidates):
        if cand in low:
            return idx + 100
    return None


def _extract_scan_from_pair(
    name: str,
    source_path: Path,
    two_theta: np.ndarray,
    intensity: np.ndarray,
    attrs: dict[str, Any],
    default_anode: str,
) -> ScanData:
    two_theta = np.asarray(two_theta, dtype=np.float64).ravel()
    intensity = np.asarray(intensity, dtype=np.float64).ravel()
    if two_theta.size != intensity.size or two_theta.size < 5:
        raise ValueError(f"Mismatched or short arrays ({two_theta.size} vs {intensity.size}) in {name}")

    order = np.argsort(two_theta)
    two_theta = two_theta[order]
    intensity = intensity[order]

    wl: float | None = None
    anode: str | None = None
    counting_time = 1.0

    for k, v in attrs.items():
        kl = k.lower()
        if "anode" in kl or "target" in kl:
            anode = _normalize_anode(v)
        elif "wavelength" in kl or "ka1" in kl:
            try:
                wl = float(v)
            except (TypeError, ValueError):
                pass
        elif "count" in kl and "time" in kl:
            try:
                counting_time = float(v)
            except (TypeError, ValueError):
                pass

    resolved_anode = anode or _infer_anode_from_wavelength(wl) or _normalize_anode(default_anode)
    return ScanData(
        name=name,
        source_path=str(source_path),
        source_format="hdf5",
        two_theta=two_theta,
        intensity=intensity,
        anode=resolved_anode,
        wavelength_ka1=wl,
        counting_time=counting_time,
        metadata=attrs,
    )


def _find_1d_pair_in_group(group: Any) -> tuple[np.ndarray, np.ndarray] | None:
    """Heuristically extract (two_theta, intensity) from datasets within a single HDF5 group."""
    import h5py

    angle_cands: list[tuple[int, np.ndarray]] = []
    inten_cands: list[tuple[int, np.ndarray, dict[str, Any]]] = []
    two_col_cands: list[np.ndarray] = []

    for key in group.keys():
        obj = group[key]
        if not isinstance(obj, h5py.Dataset):
            continue
        arr = np.asarray(obj[()])
        if arr.ndim == 2 and (arr.shape[0] == 2 or arr.shape[1] == 2) and max(arr.shape) >= 5:
            two_col_cands.append(arr if arr.shape[1] == 2 else arr.T)
            continue
        if arr.ndim != 1 or arr.size < 5 or not np.issubdtype(arr.dtype, np.number):
            continue

        a_prio = _match_key_priority(key, _ANGLE_KEYS)
        if a_prio is not None:
            angle_cands.append((a_prio, arr))
        i_prio = _match_key_priority(key, _INTENSITY_KEYS)
        if i_prio is not None:
            ds_attrs = {str(k): _decode_attr(v) for k, v in obj.attrs.items()}
            inten_cands.append((i_prio, arr, ds_attrs))

    angle_cands.sort(key=lambda x: x[0])
    inten_cands.sort(key=lambda x: x[0])

    # Pair matching-length angle and intensity datasets.
    for _, ang in angle_cands:
        for _, inten, _ in inten_cands:
            if ang.size == inten.size:
                return ang, inten

    # Fallback 1: intensity dataset paired with start/step attributes.
    if inten_cands:
        _, inten, ds_attrs = inten_cands[0]
        g_attrs = {str(k): _decode_attr(v) for k, v in group.attrs.items()}
        combined = {**g_attrs, **ds_attrs}
        start = None
        step = None
        stop = None
        for k, v in combined.items():
            kl = k.lower()
            if kl in ("start", "start_angle", "start_2theta", "startposition"):
                start = float(v)
            elif kl in ("step", "step_size", "increment", "delta_2theta"):
                step = float(v)
            elif kl in ("stop", "end", "end_angle", "end_2theta", "endposition"):
                stop = float(v)
        if start is not None and step is not None:
            ang = start + np.arange(inten.size, dtype=np.float64) * step
            return ang, inten
        if start is not None and stop is not None:
            ang = np.linspace(start, stop, inten.size, dtype=np.float64)
            return ang, inten

    # Fallback 2: 2D (N, 2) dataset.
    if two_col_cands:
        arr2 = two_col_cands[0]
        return arr2[:, 0], arr2[:, 1]

    return None


def read_hdf5_file(
    filepath: str | Path,
    angle_dataset: str | None = None,
    intensity_dataset: str | None = None,
    default_anode: str = "Cu",
) -> list[ScanData]:
    """Read one or more 1D XRD scans from an Anton Paar / generic HDF5 file (read-only)."""
    import h5py

    path = Path(filepath)
    if not path.is_file():
        raise FileNotFoundError(f"HDF5 file not found: {path}")

    with h5py.File(path, "r") as h5f:
        # 1. Explicit dataset paths configured by the user.
        if angle_dataset and intensity_dataset:
            ang_ds = h5f.get(angle_dataset.strip())
            int_ds = h5f.get(intensity_dataset.strip())
            if isinstance(ang_ds, h5py.Dataset) and isinstance(int_ds, h5py.Dataset):
                parent_group = intensity_dataset.strip().rsplit("/", 1)[0] or "/"
                attrs = _collect_group_attrs(h5f, parent_group)
                return [
                    _extract_scan_from_pair(
                        name=path.stem,
                        source_path=path,
                        two_theta=ang_ds[()],
                        intensity=int_ds[()],
                        attrs=attrs,
                        default_anode=default_anode,
                    )
                ]

        # 2. Automatic hierarchical discovery across all groups.
        discovered: list[tuple[str, np.ndarray, np.ndarray, dict[str, Any]]] = []

        def visit_group(grp: Any, grp_path: str) -> None:
            pair = _find_1d_pair_in_group(grp)
            if pair is not None:
                attrs = _collect_group_attrs(h5f, grp_path)
                discovered.append((grp_path, pair[0], pair[1], attrs))
            for key in grp.keys():
                child = grp[key]
                if isinstance(child, h5py.Group):
                    next_path = f"{grp_path.rstrip('/')}/{key}"
                    visit_group(child, next_path)

        visit_group(h5f, "/")

        if not discovered:
            raise ValueError(
                f"Could not auto-detect 2Theta/Intensity 1D datasets in {path.name}. "
                "Inspect its HDF5 tree in the UI and specify dataset paths if needed."
            )

        scans: list[ScanData] = []
        multi = len(discovered) > 1
        for idx, (grp_path, ang, inten, attrs) in enumerate(discovered, start=1):
            suffix = grp_path.strip("/").replace("/", "_") or f"scan{idx}"
            scan_name = f"{path.stem}_{suffix}" if multi else path.stem
            scans.append(
                _extract_scan_from_pair(
                    name=scan_name,
                    source_path=path,
                    two_theta=ang,
                    intensity=inten,
                    attrs=attrs,
                    default_anode=default_anode,
                )
            )
        return scans


def _xml_local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def _xml_first(el: Any, name: str) -> Any:
    for node in el.iter():
        if _xml_local(node.tag) == name:
            return node
    return None


def read_xrdml_file(filepath: str | Path, default_anode: str = "Cu") -> list[ScanData]:
    """Read a PANalytical .xrdml file (any 1.x schema) without modifying it."""
    import xml.etree.ElementTree as ET

    path = Path(filepath)
    if not path.is_file():
        raise FileNotFoundError(f"XRDML file not found: {path}")
    root = ET.parse(path).getroot()

    wl: float | None = None
    ka1_el = _xml_first(root, "kAlpha1")
    if ka1_el is not None and ka1_el.text:
        try:
            wl = float(ka1_el.text)
        except ValueError:
            wl = None
    anode_el = _xml_first(root, "anodeMaterial")
    anode = _normalize_anode(anode_el.text) if anode_el is not None and anode_el.text else None
    anode = anode or _infer_anode_from_wavelength(wl) or _normalize_anode(default_anode)

    sample_name = path.stem
    sample_el = _xml_first(root, "sample")
    if sample_el is not None:
        nm = _xml_first(sample_el, "name")
        if nm is not None and nm.text and nm.text.strip():
            sample_name = nm.text.strip()

    scan_els = [n for n in root.iter() if _xml_local(n.tag) == "scan"]
    scans: list[ScanData] = []
    for idx, sc in enumerate(scan_els, start=1):
        dp = _xml_first(sc, "dataPoints")
        if dp is None:
            continue
        inten_el = _xml_first(dp, "intensities")
        if inten_el is None:
            inten_el = _xml_first(dp, "counts")
        if inten_el is None or not (inten_el.text or "").strip():
            continue
        y = np.asarray([float(v) for v in inten_el.text.split()], dtype=np.float64)

        pos_els = [n for n in dp if _xml_local(n.tag) == "positions"]
        pos = next((n for n in pos_els if (n.get("axis") or "").lower() == "2theta"), pos_els[0] if pos_els else None)
        if pos is None:
            continue
        lp = _xml_first(pos, "listPositions")
        if lp is not None and (lp.text or "").strip():
            x = np.asarray([float(v) for v in lp.text.split()], dtype=np.float64)
        else:
            sp = _xml_first(pos, "startPosition")
            ep = _xml_first(pos, "endPosition")
            if sp is None or ep is None:
                continue
            x = np.linspace(float(sp.text), float(ep.text), y.size)
        if x.size != y.size or y.size < 5:
            continue

        cct_el = _xml_first(dp, "commonCountingTime")
        try:
            cct = float(cct_el.text) if cct_el is not None and cct_el.text else 1.0
        except ValueError:
            cct = 1.0

        order = np.argsort(x)
        scans.append(
            ScanData(
                name=path.stem if len(scan_els) == 1 else f"{path.stem}_scan{idx}",
                source_path=str(path),
                source_format="xrdml",
                two_theta=x[order],
                intensity=y[order],
                anode=anode,
                wavelength_ka1=wl,
                counting_time=cct,
                metadata={"Sample": sample_name},
            )
        )
    if not scans:
        raise ValueError(f"No readable 2Theta scan found in {path.name}")
    return scans


def read_asc_file(filepath: str | Path, default_anode: str = "Cu") -> list[ScanData]:
    """Read .asc: Rigaku '*KEY = value' header + intensities, or plain 2-column ASCII."""
    path = Path(filepath)
    if not path.is_file():
        raise FileNotFoundError(f"ASC file not found: {path}")
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    if not any(ln.lstrip().startswith("*") for ln in lines[:60]):
        return read_xy_file(path, default_anode=default_anode, source_format="asc")

    keys: dict[str, str] = {}
    values: list[float] = []
    key_re = re.compile(r"^\*([A-Za-z0-9_]+)\s*(?:=|\t|\s)\s*(.*)$")
    started = False
    for raw in lines:
        ln = raw.strip()
        if not ln:
            continue
        if ln.startswith("*"):
            if started and ln.upper().startswith(("*START", "*END")):
                break  # only the first data block
            m = key_re.match(ln)
            if m:
                keys[m.group(1).upper()] = m.group(2).strip().strip('"')
            continue
        nums = re.findall(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?", ln)
        if nums:
            started = True
            values.extend(float(v) for v in nums)

    def _num(*names: str) -> float | None:
        for n in names:
            if n in keys:
                try:
                    return float(re.findall(r"[+-]?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?", keys[n])[0])
                except (IndexError, ValueError):
                    pass
        return None

    start = _num("START")
    step = _num("STEP")
    stop = _num("STOP")
    if start is None or len(values) < 5:
        raise ValueError(f"Unrecognised Rigaku ASC layout in {path.name}")
    if step:
        x = start + np.arange(len(values)) * step
    elif stop is not None:
        x = np.linspace(start, stop, len(values))
    else:
        raise ValueError(f"ASC file {path.name} has no *STEP or *STOP")
    wl = _num("WAVE_LENGTH1", "WAVELENGTH1", "WAVE_LENGTH")
    anode = _normalize_anode(keys.get("TARGET") or keys.get("ANODE")) if (keys.get("TARGET") or keys.get("ANODE")) else None
    anode = anode or _infer_anode_from_wavelength(wl) or _normalize_anode(default_anode)
    return [
        ScanData(
            name=path.stem,
            source_path=str(path),
            source_format="asc",
            two_theta=np.asarray(x, dtype=np.float64),
            intensity=np.asarray(values, dtype=np.float64),
            anode=anode,
            wavelength_ka1=wl,
            counting_time=_num("SPEED_TIME", "COUNT_TIME") or 1.0,
            metadata={k: v for k, v in keys.items() if len(v) < 200},
        )
    ]


def _grid(start: float, step: float, count: int, offset: float = 0.0) -> np.ndarray:
    """2Theta grid start + (i + offset) * step, computed in decimal arithmetic from the stored
    float64 values so no binary rounding noise (2.0300000000000002) is added to the angles."""
    d_start = Decimal(repr(float(start)))
    d_step = Decimal(repr(float(step)))
    d_off = Decimal(repr(float(offset)))
    return np.array([float(d_start + (i + d_off) * d_step) for i in range(count)], dtype=np.float64)


def _cstr(buf: bytes, offset: int, length: int) -> str:
    return buf[offset : offset + length].split(b"\0", 1)[0].decode("latin-1").strip()


def read_bruker_raw_file(filepath: str | Path, default_anode: str = "Cu") -> list[ScanData]:
    """Read a Bruker DIFFRAC .raw file, version 3 ('RAW1.01'), read-only.  One ScanData per range.

    Layout (little-endian): 712-byte file header (12 uint32 range count, 326 char[60] sample id,
    608 char[4] anode, 624/632/648 float64 Ka1/Ka2/ratio).  Each range: header whose first uint32
    is its length (+4 uint32 steps, +16 float64 start 2Theta, +176 float64 step, +192 float32
    time/step, +240 float64 wavelength, +252 uint32 datum size, +256 uint32 supplementary header
    size), then the supplementary header, then float32[steps].  Intensities are returned exactly
    as stored.  Other RAW versions are refused until a sample validates them.
    """
    path = Path(filepath)
    if not path.is_file():
        raise FileNotFoundError(f"RAW file not found: {path}")
    buf = path.read_bytes()
    if not buf.startswith(b"RAW1.01"):
        tag = buf[:7].split(b"\0", 1)[0].decode("latin-1", "replace")
        if buf.startswith((b"RAW4", b"RAW2", b"RAW ")):
            raise ValueError(f"{path.name}: Bruker .raw version '{tag}' is not supported yet (send a sample file to validate it)")
        raise ValueError(f"{path.name} is not a Bruker .raw file")
    if len(buf) < 712:
        raise ValueError(f"{path.name}: truncated Bruker .raw header")
    n_ranges = struct.unpack_from("<I", buf, 12)[0]
    sample = _cstr(buf, 326, 60) or path.stem
    anode_txt = _cstr(buf, 608, 4)
    ka1, ka2 = struct.unpack_from("<2d", buf, 624)
    ratio = struct.unpack_from("<d", buf, 648)[0]
    file_wl = ka1 if 0.3 < ka1 < 3.0 else None
    anode = (
        (_normalize_anode(anode_txt) if anode_txt else None)
        or _infer_anode_from_wavelength(file_wl)
        or _normalize_anode(default_anode)
    )
    scans: list[ScanData] = []
    pos = 712
    for idx in range(n_ranges):
        if pos + 260 > len(buf):
            raise ValueError(f"{path.name}: range {idx + 1} header runs past end of file")
        hdr_len, steps = struct.unpack_from("<II", buf, pos)
        start = struct.unpack_from("<d", buf, pos + 16)[0]
        step = struct.unpack_from("<d", buf, pos + 176)[0]
        time_step = struct.unpack_from("<f", buf, pos + 192)[0]
        range_wl = struct.unpack_from("<d", buf, pos + 240)[0]
        datum, supp = struct.unpack_from("<II", buf, pos + 252)
        if hdr_len < 260 or datum not in (0, 4) or not step > 0:
            raise ValueError(f"{path.name}: unexpected layout in range {idx + 1} header")
        data_at = pos + hdr_len + supp
        end_at = data_at + 4 * steps
        if end_at > len(buf):
            raise ValueError(f"{path.name}: range {idx + 1} data runs past end of file")
        y = np.frombuffer(buf, dtype="<f4", count=steps, offset=data_at).astype(np.float64)
        wl = range_wl if 0.3 < range_wl < 3.0 else file_wl
        meta: dict[str, Any] = {
            "SourceFormat": "Bruker RAW1.01",
            "Range": idx + 1,
            "StartAngle_2Theta": start,
            "StepSize_2Theta": step,
            "TimePerStep": float(time_step),
            "Sample": sample,
        }
        if 0.3 < ka2 < 3.0:
            meta["Ka2"] = ka2
            meta["Ka2Ka1Ratio"] = ratio
        scans.append(
            ScanData(
                name=path.stem if n_ranges == 1 else f"{path.stem}_range{idx + 1}",
                source_path=str(path),
                source_format="raw",
                two_theta=_grid(start, step, steps),
                intensity=y,
                anode=anode,
                wavelength_ka1=wl,
                counting_time=float(time_step) if time_step > 0 else 1.0,
                metadata=meta,
            )
        )
        pos = end_at
    if pos != len(buf):
        raise ValueError(f"{path.name}: {len(buf) - pos} unexplained trailing bytes after the last range")
    if not scans:
        raise ValueError(f"{path.name}: no scan ranges found")
    return scans


def read_scan_file(
    filepath: str | Path,
    angle_dataset: str | None = None,
    intensity_dataset: str | None = None,
    default_anode: str = "Cu",
) -> list[ScanData]:
    """Dispatch reader by extension."""
    path = Path(filepath)
    ext = path.suffix.lower()
    if ext in (".hdf5", ".h5"):
        return read_hdf5_file(
            path,
            angle_dataset=angle_dataset,
            intensity_dataset=intensity_dataset,
            default_anode=default_anode,
        )
    if ext == ".xrdml":
        return read_xrdml_file(path, default_anode=default_anode)
    if ext == ".asc":
        return read_asc_file(path, default_anode=default_anode)
    if ext == ".raw":
        return read_bruker_raw_file(path, default_anode=default_anode)
    if ext in (".xy", ".xye", ".txt", ".dat"):
        return read_xy_file(path, default_anode=default_anode, source_format=ext.lstrip(".").replace("xye", "xy").replace("txt", "xy"))
    raise ValueError(f"Unsupported input scan extension '{ext}' for {path.name}")


def convert_wavelength(scan: ScanData, source_anode: str, target_anode: str) -> ScanData:
    """Re-map 2Theta from the source Kα1 wavelength to the target anode's Kα1 (Bragg's law).

    d = λ_src / (2 sin θ)  ->  2θ' = 2 asin(λ_tgt / (2d)).  Points that fall beyond 2θ'=180°
    (possible when moving to a longer wavelength) cannot exist physically and are dropped.
    The intensity of every point is kept exactly; only its 2Theta position moves.  No
    interpolation or resampling is done (the new 2Theta grid is therefore non-uniform).
    """
    src_key = _normalize_anode(source_anode)
    tgt_key = _normalize_anode(target_anode)
    lam_src = ANODE_WAVELENGTHS[src_key]["kAlpha1"]
    lam_tgt = ANODE_WAVELENGTHS[tgt_key]["kAlpha1"]

    arg = (lam_tgt / lam_src) * np.sin(np.radians(scan.two_theta / 2.0))
    mask = (arg > 0) & (arg < 1)
    if int(mask.sum()) < 5:
        raise ValueError(f"Too few points remain after converting {scan.name} from {src_key} to {tgt_key}")
    new_tt = 2.0 * np.degrees(np.arcsin(arg[mask]))
    y = scan.intensity[mask].copy()  # intensities are carried over untouched, point for point
    dropped = int(scan.two_theta.size - new_tt.size)

    meta = dict(scan.metadata)
    meta["WavelengthConversion"] = (
        f"{src_key} Ka1 {lam_src:.6f} A -> {tgt_key} Ka1 {lam_tgt:.6f} A (Bragg, d preserved, "
        f"intensities unchanged, {dropped} point(s) beyond 180 deg dropped)"
    )
    meta["WavelengthDroppedPoints"] = dropped
    return ScanData(
        name=scan.name,
        source_path=scan.source_path,
        source_format=scan.source_format,
        two_theta=new_tt,
        intensity=y,
        anode=tgt_key,
        wavelength_ka1=None,
        counting_time=scan.counting_time,
        metadata=meta,
    )


def write_xy_file(scan: ScanData, out_path: str | Path, anode_override: str | None = None) -> Path:
    """Export ScanData to a 2-column .xy / .dat text file with a commented header."""
    target = Path(out_path)
    _guard_output_path(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    anode, wl = scan.resolved_wavelengths(anode_override)
    lines = [
        f"# Generator: XRD {BRIDGE_MARKER} (non-destructive conversion)",
        f"# Source: {Path(scan.source_path).name}",
        f"# Sample: {scan.name}",
        f"# Anode: {anode}",
        f"# Wavelength: {wl['kAlpha1']:.6f}",
    ]
    if scan.metadata.get("WavelengthConversion"):
        lines.append(f"# Converted: {scan.metadata['WavelengthConversion']}")
    lines.append("# Columns: 2Theta(deg) Intensity(counts)")
    lines.extend(f"{fmt_num(x)} {fmt_num(y)}" for x, y in zip(scan.two_theta, scan.intensity))
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return target


def write_bruker_raw_file(scan: ScanData, out_path: str | Path, anode_override: str | None = None) -> Path:
    """Export ScanData to a Bruker DIFFRAC .raw file, version 3 ('RAW1.01'), one range.

    Same layout read_bruker_raw_file() reads.  RAW stores intensities as float32 and the angles
    only as start + step, so the file is written only if both hold the data exactly: every
    intensity must be representable as float32 (all integer counts up to 16,777,216 are) and the
    2Theta grid must be uniform (is_exactly_uniform).  Otherwise ValueError is raised and nothing
    is written.
    """
    target = Path(out_path)
    _guard_output_path(target)
    tt = np.asarray(scan.two_theta, dtype=np.float64)
    y = np.asarray(scan.intensity, dtype=np.float64)
    if tt.size < 2 or tt.size != y.size:
        raise ValueError(f"{scan.name}: need at least two points to write Bruker .raw")
    if not is_exactly_uniform(tt):
        raise ValueError(
            "Bruker .raw stores only start and step; this scan's 2Theta grid is not uniform, "
            "so writing it would move data points."
        )
    y32 = y.astype("<f4")
    if not np.array_equal(y32.astype(np.float64), y):
        raise ValueError(
            "Bruker .raw stores intensities as 32-bit floats; some intensities in this scan would "
            "be rounded, so .raw was not written."
        )
    anode, wl = scan.resolved_wavelengths(anode_override)
    start = float(tt[0])
    step = (float(tt[-1]) - start) / (tt.size - 1)
    now = dt.datetime.now()

    def put_str(buf: bytearray, offset: int, length: int, text: str) -> None:
        raw = text.encode("latin-1", "replace")[: length - 1]
        buf[offset : offset + len(raw)] = raw

    head = bytearray(712)
    head[0:8] = b"RAW1.01\0"
    struct.pack_into("<II", head, 8, 1, 1)  # status: completed; one range
    put_str(head, 16, 10, now.strftime("%m/%d/%y"))
    put_str(head, 26, 10, now.strftime("%H:%M:%S"))
    put_str(head, 326, 60, scan.name)
    put_str(head, 386, 160, f"Converted by XRD Data Bridge ({BRIDGE_MARKER}) from {Path(scan.source_path).name}")
    put_str(head, 608, 4, anode)
    ka1, ka2 = float(wl["kAlpha1"]), float(wl["kAlpha2"])
    ratio = float(wl.get("ratio", 0.5))
    ka_avg = (2 * ka1 + ka2) / 3 if ratio == 0.5 else (ka1 + ratio * ka2) / (1 + ratio)
    struct.pack_into("<5d", head, 616, ka_avg, ka1, ka2, float(wl["kBeta"]), ratio)

    rng = bytearray(304)
    struct.pack_into("<II", rng, 0, 304, tt.size)
    struct.pack_into("<2d", rng, 8, start / 2.0, start)
    struct.pack_into("<d", rng, 176, step)
    struct.pack_into("<f", rng, 192, float(scan.counting_time or 1.0))
    struct.pack_into("<d", rng, 240, ka1)
    struct.pack_into("<II", rng, 252, 4, 0)  # datum size, supplementary header size

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(bytes(head) + bytes(rng) + y32.tobytes())
    return target


def write_asc_file(
    scan: ScanData,
    out_path: str | Path,
    asc_flavor: str = "panalytical_2col",
    anode_override: str | None = None,
) -> Path:
    """Export ScanData to .asc (PANalytical 2-column ASCII or Rigaku ASC)."""
    target = Path(out_path)
    _guard_output_path(target)
    target.parent.mkdir(parents=True, exist_ok=True)

    _, wl = scan.resolved_wavelengths(anode_override)
    two_theta = scan.two_theta
    intensity = scan.intensity

    lines: list[str] = []
    if asc_flavor == "rigaku_asc":
        if not is_exactly_uniform(two_theta):
            raise ValueError(
                "Rigaku ASC stores only START/STEP; this scan's 2Theta grid is not uniform, "
                "so writing it would move data points. Use the PANalytical 2-column .asc instead."
            )
        step = (float(two_theta[-1]) - float(two_theta[0])) / (two_theta.size - 1)
        lines.append("*TYPE_RAW")
        lines.append(f"*SAMPLE\t{scan.name}")
        lines.append(f"*START\t{fmt_num(two_theta[0])}")
        lines.append(f"*STOP\t{fmt_num(two_theta[-1])}")
        lines.append(f"*STEP\t{fmt_num(step)}")
        lines.append(f"*WAVE_LENGTH1\t{wl['kAlpha1']:.6f}")
        lines.append(f"*WAVE_LENGTH2\t{wl['kAlpha2']:.6f}")
        lines.append(f"*COUNT\t{two_theta.size}")
        for val in intensity:
            lines.append(fmt_num(val))
        lines.append("*END")
    else:
        # Standard clean 2-column tab-delimited ASCII accepted natively by HighScore Plus & Data Viewer.
        for x_val, y_val in zip(two_theta, intensity):
            lines.append(f"{fmt_num(x_val)}\t{fmt_num(y_val)}")

    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return target


def write_xrdml_file(
    scan: ScanData,
    out_path: str | Path,
    anode_override: str | None = None,
    tension_kv: float | None = None,
    current_ma: float | None = None,
) -> Path:
    """Export ScanData to strict PANalytical XRDML v1.3 XML compatible with HighScore Plus & Data Viewer."""
    target = Path(out_path)
    _guard_output_path(target)
    target.parent.mkdir(parents=True, exist_ok=True)

    anode, wl = scan.resolved_wavelengths(anode_override)
    kv = float(tension_kv or scan.metadata.get("Tension_kV") or scan.metadata.get("tension_kv") or 40.0)
    ma = float(current_ma or scan.metadata.get("Current_mA") or scan.metadata.get("current_ma") or 40.0)

    two_theta = scan.two_theta
    intensity = scan.intensity

    is_uniform = is_exactly_uniform(two_theta)

    now_iso = dt.datetime.now().strftime("%Y-%m-%dT%H:%M:%S")
    start_ts = str(scan.metadata.get("StartTimeStamp") or now_iso)
    end_ts = str(scan.metadata.get("EndTimeStamp") or now_iso)
    src_instrument = str(scan.metadata.get("Instrument") or "source instrument")

    if is_uniform:
        start_2th = float(two_theta[0])
        end_2th = float(two_theta[-1])
        positions_xml = (
            f'\t\t\t\t<positions axis="2Theta" unit="deg">\n'
            f"\t\t\t\t\t<startPosition>{fmt_num(start_2th)}</startPosition>\n"
            f"\t\t\t\t\t<endPosition>{fmt_num(end_2th)}</endPosition>\n"
            f"\t\t\t\t</positions>\n"
            f'\t\t\t\t<positions axis="Omega" unit="deg">\n'
            f"\t\t\t\t\t<startPosition>{fmt_num(start_2th / 2.0)}</startPosition>\n"
            f"\t\t\t\t\t<endPosition>{fmt_num(end_2th / 2.0)}</endPosition>\n"
            f"\t\t\t\t</positions>\n"
        )
    else:
        pos_str = " ".join(fmt_num(x) for x in two_theta)
        positions_xml = (
            f'\t\t\t\t<positions axis="2Theta" unit="deg">\n'
            f"\t\t\t\t\t<listPositions>{pos_str}</listPositions>\n"
            f"\t\t\t\t</positions>\n"
        )

    inten_str = " ".join(fmt_num(y) for y in intensity)

    xml_text = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<xrdMeasurements xmlns="http://www.xrdml.com/XRDMeasurement/1.3" '
        'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
        'xsi:schemaLocation="http://www.xrdml.com/XRDMeasurement/1.3 '
        'http://www.xrdml.com/XRDMeasurement/1.3/XRDMeasurement.xsd" '
        'status="Completed">\n'
        "\t<comment>\n"
        f"\t\t<entry>Converted non-destructively from {escape(Path(scan.source_path).name)} ({escape(src_instrument)})</entry>\n"
        "\t\t<entry>Generator=XRD Data Bridge (SDL Bridge) v1.0</entry>\n"
        + (
            f"\t\t<entry>{escape(str(scan.metadata['WavelengthConversion']))}</entry>\n"
            if scan.metadata.get("WavelengthConversion")
            else ""
        )
        + "\t</comment>\n"
        '\t<sample type="To be analyzed">\n'
        f"\t\t<id>{escape(scan.name)}</id>\n"
        f"\t\t<name>{escape(scan.name)}</name>\n"
        "\t</sample>\n"
        '\t<xrdMeasurement measurementType="Scan" status="Completed" sampleMode="Reflection">\n'
        '\t\t<usedWavelength intended="K-Alpha 1">\n'
        f'\t\t\t<kAlpha1 unit="Angstrom">{wl["kAlpha1"]:.6f}</kAlpha1>\n'
        f'\t\t\t<kAlpha2 unit="Angstrom">{wl["kAlpha2"]:.6f}</kAlpha2>\n'
        f'\t\t\t<kBeta unit="Angstrom">{wl["kBeta"]:.6f}</kBeta>\n'
        f'\t\t\t<ratioKAlpha2KAlpha1>{wl["ratio"]:.6f}</ratioKAlpha2KAlpha1>\n'
        "\t\t</usedWavelength>\n"
        "\t\t<incidentBeamPath>\n"
        '\t\t\t<radius unit="mm">240.00</radius>\n'
        f'\t\t\t<xRayTube id="0" name="{escape(anode)} tube">\n'
        f'\t\t\t\t<tension unit="kV">{kv:.0f}</tension>\n'
        f'\t\t\t\t<current unit="mA">{ma:.0f}</current>\n'
        f"\t\t\t\t<anodeMaterial>{escape(anode)}</anodeMaterial>\n"
        "\t\t\t</xRayTube>\n"
        "\t\t</incidentBeamPath>\n"
        "\t\t<diffractedBeamPath>\n"
        '\t\t\t<radius unit="mm">240.00</radius>\n'
        "\t\t</diffractedBeamPath>\n"
        '\t\t<scan appendNumber="0" mode="Continuous" scanAxis="Gonio" status="Completed">\n'
        "\t\t\t<header>\n"
        f"\t\t\t\t<startTimeStamp>{escape(start_ts)}</startTimeStamp>\n"
        f"\t\t\t\t<endTimeStamp>{escape(end_ts)}</endTimeStamp>\n"
        "\t\t\t\t<author>\n"
        "\t\t\t\t\t<name>XRD Data Bridge</name>\n"
        "\t\t\t\t</author>\n"
        "\t\t\t\t<source>\n"
        '\t\t\t\t\t<applicationSoftware version="1.0">XRD Data Bridge (SDL Bridge)</applicationSoftware>\n'
        "\t\t\t\t</source>\n"
        "\t\t\t</header>\n"
        "\t\t\t<dataPoints>\n"
        f"{positions_xml}"
        f'\t\t\t\t<commonCountingTime unit="seconds">{fmt_num(scan.counting_time)}</commonCountingTime>\n'
        f'\t\t\t\t<intensities unit="counts">{inten_str}</intensities>\n'
        "\t\t\t</dataPoints>\n"
        "\t\t</scan>\n"
        "\t</xrdMeasurement>\n"
        "</xrdMeasurements>\n"
    )

    target.write_text(xml_text, encoding="utf-8")
    return target
